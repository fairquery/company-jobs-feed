// Copies the Actor's dependency-free modules into mcp/src/shared so the MCP server builds on its own
// (Glama/Docker build context = mcp/ or repo root). `--check` fails if the copies are stale.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const from = path.join(here, '..', '..', 'src');
const to = path.join(here, '..', 'src', 'shared');
const FILES = ['ats.ts', 'discovery.ts', 'filters.ts', 'gazetteer.ts', 'gem.ts', 'http.ts', 'json-array.ts', 'location-scan.ts', 'normalize.ts', 'personio.ts', 'pinpoint.ts', 'robots.ts', 'rows.ts', 'seed.ts', 'ssrf.ts', 'state.ts', 'types.ts'];
const HEADER = '// GENERATED by mcp/scripts/sync-shared.mjs from ../../src. Do not edit here.\n';
const check = process.argv.includes('--check');
let stale = 0;
for (const f of FILES) {
    const src = path.join(from, f);
    if (!existsSync(src)) {
        if (check) continue; // building from an mcp-only checkout: keep committed copies
        throw new Error(`missing ${src}`);
    }
    const want = HEADER + readFileSync(src, 'utf8');
    const dst = path.join(to, f);
    const have = existsSync(dst) ? readFileSync(dst, 'utf8') : '';
    if (have !== want) {
        if (check) {
            console.error(`stale: mcp/src/shared/${f} (run npm run sync)`);
            stale++;
        } else writeFileSync(dst, want);
    }
}
if (stale) process.exit(1);
console.log(check ? 'shared sources up to date' : `synced ${FILES.length} files`);
